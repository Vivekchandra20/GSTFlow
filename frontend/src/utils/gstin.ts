const GSTIN_REGEX = /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$/;

export function isValidGstin(gstin: string): boolean {
  if (!gstin || typeof gstin !== 'string') return false;
  const upper = gstin.trim().toUpperCase();
  if (!GSTIN_REGEX.test(upper)) return false;

  const stateCode = upper.substring(0, 2);
  if (!INDIAN_STATES[stateCode]) return false;

  return true;
}

export function getStateNameByCode(stateCode: string): string {
  return INDIAN_STATES[stateCode] || `State (${stateCode})`;
}

export function extractPanFromGstin(gstin: string): string | null {
  if (!gstin || gstin.length < 12) return null;
  return gstin.substring(2, 12).toUpperCase();
}
